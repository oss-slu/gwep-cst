import { describe, expect, it } from "vitest";
import { parse } from "yaml";
import committedConfig from "../../public/admin/config.yml?raw";
import {
  buildCmsConfig,
  serializeCmsConfig,
} from "../../scripts/cms/config.ts";
import { testRegistry } from "../support/test-slides";

type Config = ReturnType<typeof buildCmsConfig>;

function slideTypes(config: Config) {
  const slides = config.collections[0]?.fields.find(
    (field) => field.name === "slides",
  );
  return slides !== undefined && "types" in slides ? slides.types : [];
}

describe("CMS config generation", () => {
  it("matches the committed public/admin/config.yml, read as YAML with its header", () => {
    expect(
      committedConfig.startsWith("# Generated by `npm run cms:generate`"),
    ).toBe(true);
    expect(parse(committedConfig)).toEqual(buildCmsConfig());
  });

  it("produces identical output on every run", () => {
    const modules = testRegistry.modules;
    expect(serializeCmsConfig(buildCmsConfig(modules))).toBe(
      serializeCmsConfig(buildCmsConfig(modules)),
    );
  });

  it("round-trips the complete emitted file through a YAML parser", () => {
    const config = buildCmsConfig(testRegistry.modules);
    expect(parse(serializeCmsConfig(config))).toEqual(config);
  });

  it("keeps editor labels and help text exactly, including special characters", () => {
    const parsed = parse(
      serializeCmsConfig(buildCmsConfig(testRegistry.modules)),
    ) as Config;
    const textType = slideTypes(parsed).find(
      (type) => type.name === "test-text",
    );
    const textField = textType?.fields.find((field) => field.name === "text");

    expect(textType?.label).toBe("Test: text");
    expect(textField?.label).toBe("Text");
    expect(textField?.hint).toBe(
      'Quotes "like this", a colon: and a # stay as written.\nSecond line; café.',
    );
  });

  it("lists one slide type per registered module, in registry order, with the shared fields first", () => {
    const types = slideTypes(buildCmsConfig(testRegistry.modules));
    expect(types.map((type) => type.name)).toEqual(["test-text", "test-media"]);
    for (const type of types) {
      expect(type.fields.slice(0, 2).map((field) => field.name)).toEqual([
        "id",
        "notes",
      ]);
    }
    const media = types.find((type) => type.name === "test-media");
    expect(media?.fields.map((field) => field.name)).toEqual([
      "id",
      "notes",
      "image",
      "sound",
    ]);
  });

  it("has no slide types in production yet (provisional until #8)", () => {
    expect(slideTypes(buildCmsConfig())).toEqual([]);
  });
});
